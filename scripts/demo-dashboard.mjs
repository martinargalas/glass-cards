// examples/demo.yaml + demo-popups.yaml → src/demo/dashboard.ts: the demo dashboard (and its
// pop-ups) Dashboard Studio adds to HA with one click and the web demo shows. The YAML is the
// source; never edit the .ts.
import { readFileSync, writeFileSync } from "node:fs";
import { parse } from "yaml";

const read = (f) => parse(readFileSync(new URL(`../examples/${f}`, import.meta.url), "utf8"));
const out = `// Generated by scripts/demo-dashboard.mjs from examples/demo.yaml and demo-popups.yaml – edit the YAML instead.
/* eslint-disable */
export const DEMO_DASHBOARD: Record<string, any> = ${JSON.stringify(read("demo.yaml"))};
export const DEMO_POPUPS: Record<string, any> = ${JSON.stringify(read("demo-popups.yaml"))};
/** Where the pop-ups live: the demo dashboard's overlay_source points here. */
export const DEMO_POPUPS_URL = "glass-demo-popups";
`;
writeFileSync(new URL("../src/demo/dashboard.ts", import.meta.url), out);
console.log("demo dashboard: examples/demo*.yaml → src/demo/dashboard.ts");
