// examples/demo.yaml → src/demo/dashboard.ts: the demo dashboard Glass Studio adds to HA
// with one click (and the web demo shows). The YAML is the source; never edit the .ts.
import { readFileSync, writeFileSync } from "node:fs";
import { parse } from "yaml";

const cfg = parse(readFileSync(new URL("../examples/demo.yaml", import.meta.url), "utf8"));
const out = `// Generated by scripts/demo-dashboard.mjs from examples/demo.yaml – edit the YAML instead.
/* eslint-disable */
export const DEMO_DASHBOARD: Record<string, any> = ${JSON.stringify(cfg)};
`;
writeFileSync(new URL("../src/demo/dashboard.ts", import.meta.url), out);
console.log("demo dashboard: examples/demo.yaml → src/demo/dashboard.ts");
